for t in ("device", "patient"):
    h = pd.read_csv(d / f"pii_{t}.tsv", sep="\t")
    s = h[h.pattern == "honorific"].copy()
    s["word"] = s.match.str.upper().str.replace(r"^(DR|MR|MRS|MS|MISS)\.?\s+", "", regex=True).str.strip(".,")
